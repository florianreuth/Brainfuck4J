package de.florianreuth.brainfuck4j.export;

import de.florianreuth.brainfuck4j.EndOfInput;
import de.florianreuth.brainfuck4j.Instruction;
import de.florianreuth.brainfuck4j.InstructionType;
import de.florianreuth.brainfuck4j.MemoryType;
import de.florianreuth.brainfuck4j.Program;

import javax.lang.model.SourceVersion;
import java.util.ArrayList;
import java.util.List;

/**
 * Exports a {@link Program} as a standalone Java source file with a main method.
 * <p>
 * Long instruction sequences are split into separate methods to stay below the bytecode size limits of javac and the JIT.
 */
public final class JavaExporter {

    private static final int CHUNK_SIZE = 64;

    private final List<Instruction> instructions;
    private final MemoryType type;
    private final List<SourceWriter> methods = new ArrayList<>();

    private JavaExporter(final Program program, final MemoryType type) {
        this.instructions = program.instructions();
        this.type = type;
    }

    /**
     * @param program    The program to export.
     * @param type       The cell width.
     * @param size       The number of cells, out of bounds access throws in the generated code.
     * @param endOfInput The value stored by input instructions once the input has ended.
     * @param className  The name of the generated class, must match the file name.
     * @return The Java source code.
     * @throws IllegalArgumentException If size is not positive or the class name is not a valid Java identifier.
     */
    public static String export(final Program program, final MemoryType type, final int size, final EndOfInput endOfInput, final String className) {
        if (size <= 0) {
            throw new IllegalArgumentException("Memory size must be positive: " + size);
        }

        if (!SourceVersion.isName(className) || className.contains(".")) {
            throw new IllegalArgumentException("Invalid Java class name: " + className);
        }

        final JavaExporter exporter = new JavaExporter(program, type);
        final SourceWriter main = new SourceWriter(2);
        main.line("int p = 0;");
        exporter.range(main, 0, exporter.instructions.size());
        main.line("O.flush();");

        final String array = switch (type) {
            case BIT_8 -> "byte";
            case BIT_16 -> "short";
            case BIT_32 -> "int";
        };
        final SourceWriter writer = new SourceWriter(0);
        writer.line("// Generated by Brainfuck4J");
        writer.line("import java.io.BufferedOutputStream;");
        writer.line("import java.io.FileDescriptor;");
        writer.line("import java.io.FileOutputStream;");
        writer.line("import java.io.IOException;");
        writer.line("import java.io.InputStream;");
        writer.line("import java.io.OutputStream;");
        writer.blank();
        writer.open("public final class " + className + " {");
        writer.blank();
        writer.line("private static final " + array + "[] M = new " + array + "[" + size + "];");
        writer.line("private static final InputStream I = System.in;");
        writer.line("private static final OutputStream O = new BufferedOutputStream(new FileOutputStream(FileDescriptor.out));");
        writer.blank();
        writer.open("public static void main(final String[] a) throws IOException {");
        writer.append(main);
        writer.close("}");
        for (int i = 0; i < exporter.methods.size(); i++) {
            writer.blank();
            writer.open("private static int b" + i + "(int p) throws IOException {");
            writer.append(exporter.methods.get(i));
            writer.line("return p;");
            writer.close("}");
        }

        writer.blank();
        writer.open("private static void w(final int v) throws IOException {");
        writer.line("O.write(v);");
        writer.open("if ((byte) v == '\\n') {");
        writer.line("O.flush();");
        writer.close("}");
        writer.close("}");
        writer.blank();
        writer.open("private static int r(final int v) throws IOException {");
        writer.line("O.flush();");
        writer.line("final int c = I.read();");
        writer.line("return c == -1 ? " + switch (endOfInput) {
            case MINUS_ONE -> "-1";
            case ZERO -> "0";
            case UNCHANGED -> "v";
        } + " : (byte) c;");
        writer.close("}");
        writer.blank();
        writer.close("}");
        return writer.toString();
    }

    private void range(final SourceWriter writer, final int from, final int to) {
        if (to - from <= CHUNK_SIZE) {
            this.units(writer, from, to);
            return;
        }

        int start = from;
        while (start < to) {
            int end = this.unitEnd(start);
            while (end < to && this.unitEnd(end) - start <= CHUNK_SIZE) {
                end = this.unitEnd(end);
            }

            if (this.unitEnd(start) == end && this.instructions.get(start).type() == InstructionType.LOOP_START) {
                // A single oversized loop stays inline, its body gets split recursively instead
                this.units(writer, start, end);
            } else {
                final SourceWriter method = new SourceWriter(2);
                writer.line("p = b" + this.methods.size() + "(p);");
                this.methods.add(method);
                this.units(method, start, end);
            }

            start = end;
        }
    }

    private void units(final SourceWriter writer, final int from, final int to) {
        for (int i = from; i < to; i = this.unitEnd(i)) {
            this.unit(writer, i);
        }
    }

    private int unitEnd(final int index) {
        final Instruction instruction = this.instructions.get(index);
        return switch (instruction.type()) {
            case LOOP_START, LOAD -> instruction.value() + 1;
            default -> index + 1;
        };
    }

    private void unit(final SourceWriter writer, final int index) {
        final Instruction instruction = this.instructions.get(index);
        final int value = instruction.value();
        final String cell = cell(instruction.offset());
        switch (instruction.type()) {
            case ADD -> writer.line(cell + operator(value) + magnitude(value) + ";");
            case SET -> writer.line(cell + " = " + (value << (32 - this.type.bits) >> (32 - this.type.bits)) + ";");
            case MOVE -> writer.line("p" + operator(value) + magnitude(value) + ";");
            case LOOP_START -> {
                move(writer, instruction.offset());
                writer.open("while (M[p] != 0) {");
                this.range(writer, index + 1, value);
                move(writer, this.instructions.get(value).offset());
                writer.close("}");
            }
            case LOAD -> {
                writer.open("if (" + cell + " != 0) {");
                writer.line("final int f = " + cell + ";");
                writer.line(cell + " = 0;");
                for (int i = index + 1; i <= value; i++) {
                    final Instruction multiply = this.instructions.get(i);
                    final int factor = multiply.value();
                    writer.line(cell(multiply.offset()) + operator(factor) + (Math.abs(factor) == 1 ? "f" : "f * " + magnitude(factor)) + ";");
                }

                writer.close("}");
            }
            case SCAN -> {
                move(writer, instruction.offset());
                writer.open("while (M[p] != 0) {");
                writer.line("p" + operator(value) + magnitude(value) + ";");
                writer.close("}");
            }
            case OUTPUT -> writer.line("w(" + cell + ");");
            case INPUT -> writer.line(cell + " = " + switch (this.type) {
                case BIT_8 -> "(byte) ";
                case BIT_16 -> "(short) ";
                case BIT_32 -> "";
            } + "r(" + cell + ");");
            case LOOP_END, MULTIPLY -> throw new IllegalStateException("Unexpected " + instruction.type() + " at index " + index);
        }
    }

    private static void move(final SourceWriter writer, final int offset) {
        if (offset != 0) {
            writer.line("p" + operator(offset) + magnitude(offset) + ";");
        }
    }

    private static String cell(final int offset) {
        if (offset == 0) {
            return "M[p]";
        }

        return "M[p" + (offset < 0 ? " - " : " + ") + magnitude(offset) + "]";
    }

    private static String operator(final int value) {
        return value < 0 && value != Integer.MIN_VALUE ? " -= " : " += ";
    }

    private static String magnitude(final int value) {
        // Integer.MIN_VALUE has no positive int counterpart, so it is kept as negative literal
        return String.valueOf(value == Integer.MIN_VALUE ? value : Math.abs(value));
    }

}
