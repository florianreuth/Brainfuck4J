package de.florianreuth.brainfuck4j.export;

import de.florianreuth.brainfuck4j.EndOfInput;
import de.florianreuth.brainfuck4j.Instruction;
import de.florianreuth.brainfuck4j.InstructionType;
import de.florianreuth.brainfuck4j.MemoryType;
import de.florianreuth.brainfuck4j.Program;

import java.util.List;

/**
 * Exports a {@link Program} as a standalone C99 source file using unsigned cells of the memory type's width.
 */
public final class CExporter {

    private CExporter() {
    }

    /**
     * @param program    The program to export.
     * @param type       The cell width.
     * @param size       The number of cells, memory accesses are not bounds checked in the generated code.
     * @param endOfInput The value stored by input instructions once the input has ended.
     * @return The C source code.
     * @throws IllegalArgumentException If size is not positive.
     */
    public static String export(final Program program, final MemoryType type, final int size, final EndOfInput endOfInput) {
        if (size <= 0) {
            throw new IllegalArgumentException("Memory size must be positive: " + size);
        }

        final List<Instruction> instructions = program.instructions();
        final SourceWriter writer = new SourceWriter(0);
        writer.line("// Generated by Brainfuck4J");
        writer.line("#include <stdint.h>");
        writer.line("#include <stdio.h>");
        writer.blank();
        writer.line("typedef uint" + type.bits + "_t T;");
        writer.blank();
        writer.line("static T m[" + size + "];");
        writer.blank();
        if (instructions.stream().anyMatch(instruction -> instruction.type() == InstructionType.INPUT)) {
            writer.open("static T i(const T v) {");
            writer.line("fflush(stdout);");
            writer.line("const int c = getchar();");
            writer.line("return c == EOF ? " + switch (endOfInput) {
                case MINUS_ONE -> "(T) -1";
                case ZERO -> "0";
                case UNCHANGED -> "v";
            } + " : (T) (int8_t) c;");
            writer.close("}");
            writer.blank();
        }

        writer.open("int main(void) {");
        writer.line("T *p = m;");
        writer.blank();

        int closeAt = -1;
        for (int i = 0; i < instructions.size(); i++) {
            final Instruction instruction = instructions.get(i);
            final int value = instruction.value();
            final String cell = cell(instruction.offset());
            switch (instruction.type()) {
                case ADD -> writer.line(cell + operator(value) + magnitude(value) + ";");
                case SET -> writer.line(cell + " = " + (value & mask(type)) + "u;");
                case MOVE -> writer.line("p" + operator(value) + magnitude(value) + ";");
                case LOOP_START -> {
                    move(writer, instruction.offset());
                    writer.open("while (*p) {");
                }
                case LOOP_END -> {
                    move(writer, instruction.offset());
                    writer.close("}");
                }
                case LOAD -> {
                    writer.open("if (" + cell + ") {");
                    writer.line("const T f = " + cell + ";");
                    writer.line(cell + " = 0;");
                    closeAt = value;
                }
                case MULTIPLY -> writer.line(cell + operator(value) + (magnitude(value) == 1 ? "f" : "f * " + magnitude(value) + "u") + ";");
                case SCAN -> {
                    move(writer, instruction.offset());
                    writer.open("while (*p) {");
                    writer.line("p" + operator(value) + magnitude(value) + ";");
                    writer.close("}");
                }
                case OUTPUT -> writer.line("putchar(" + cell + ");");
                case INPUT -> writer.line(cell + " = i(" + cell + ");");
            }

            if (i == closeAt) {
                writer.close("}");
            }
        }

        writer.blank();
        writer.line("fflush(stdout);");
        writer.line("return 0;");
        writer.close("}");
        return writer.toString();
    }

    private static void move(final SourceWriter writer, final int offset) {
        if (offset != 0) {
            writer.line("p" + operator(offset) + magnitude(offset) + ";");
        }
    }

    private static String cell(final int offset) {
        return offset == 0 ? "*p" : "p[" + offset + "]";
    }

    private static String operator(final int value) {
        return value < 0 ? " -= " : " += ";
    }

    private static long magnitude(final int value) {
        return Math.abs((long) value);
    }

    private static long mask(final MemoryType type) {
        return (1L << type.bits) - 1;
    }

}
